import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = `${root}public/brand/logo-original.svg`;
const OUT_TS = `${root}src/brand/logo.ts`;
const OUT_MARK = `${root}public/brand/clyx-mark.svg`;
const OUT_MONO = `${root}public/brand/clyx-mark-mono.svg`;

const SYMBOL_IDS = ["wedge-lower", "arm-top", "wedge-upper", "arm-bottom", "ring"];
const CLYX_IDS = ["C", "L", "Y", "X"];
const STUDIO_IDS = ["S", "T", "U", "D", "I", "O"];
const SYMBOL_VIEWBOX = "180 100 1640 1310";
const BRAND_STOPS = ["#8D2168", "#1E2126"];

function attr(source, name) {
  const match = source.match(new RegExp(`\\b${name}="([^"]*)"`));
  return match ? match[1] : null;
}

function parse(svg) {
  const classFill = new Map();
  for (const [, cls, id] of svg.matchAll(/\.(st\d+)\{fill:url\(#([^)]+)\);\}/g)) {
    classFill.set(cls, id);
  }

  const pattern =
    /<linearGradient\b([^>]*)>([\s\S]*?)<\/linearGradient>\s*<(path|polygon)\b([^>]*?)\/>/g;
  const shapes = [];
  for (const [, gradAttrs, gradBody, tag, shapeAttrs] of svg.matchAll(pattern)) {
    const gradientId = attr(gradAttrs, "id");
    const stops = [...gradBody.matchAll(/<stop\s+offset="([^"]+)"\s+style="stop-color:([^"]+)"/g)].map(
      ([, offset, color]) => ({ offset, color }),
    );
    const geometry = attr(shapeAttrs, tag === "path" ? "d" : "points");
    const styleFill = shapeAttrs.match(/fill:url\(#([^)]+)\)/);
    const cls = attr(shapeAttrs, "class");
    const fillId = styleFill ? styleFill[1] : cls ? classFill.get(cls) : null;
    shapes.push({
      tag,
      geometry,
      fillId,
      gradientId,
      gradient: {
        x1: attr(gradAttrs, "x1"),
        y1: attr(gradAttrs, "y1"),
        x2: attr(gradAttrs, "x2"),
        y2: attr(gradAttrs, "y2"),
        units: attr(gradAttrs, "gradientUnits"),
        stops,
      },
    });
  }
  return shapes;
}

function validate(svg, shapes) {
  const errors = [];
  const gradientCount = [...svg.matchAll(/<linearGradient\b/g)].length;
  const shapeCount = [...svg.matchAll(/<(path|polygon)\b/g)].length;
  if (attr(svg, "viewBox") !== "0 0 2000 2000") errors.push("viewBox is not 0 0 2000 2000");
  if (gradientCount !== 15) errors.push(`expected 15 gradients, found ${gradientCount}`);
  if (shapeCount !== 15) errors.push(`expected 15 shapes, found ${shapeCount}`);
  if (shapes.length !== 15) errors.push(`paired ${shapes.length} gradient and shape blocks, expected 15`);
  shapes.forEach((shape, index) => {
    const label = `shape ${index}`;
    if (!shape.geometry) errors.push(`${label}: missing geometry`);
    else if (!svg.includes(`"${shape.geometry}"`)) errors.push(`${label}: geometry is not verbatim`);
    if (shape.fillId !== shape.gradientId) {
      errors.push(`${label}: fills ${shape.fillId}, expected ${shape.gradientId}`);
    }
    if (shape.gradient.units !== "userSpaceOnUse") errors.push(`${label}: gradient units changed`);
    const colors = shape.gradient.stops.map((stop) => stop.color);
    if (colors.join() !== BRAND_STOPS.join()) errors.push(`${label}: gradient stops ${colors.join()}`);
  });
  return errors;
}

function grouped(shapes) {
  const pick = (from, ids) =>
    ids.map((id, offset) => {
      const { tag, geometry, gradient } = shapes[from + offset];
      const { x1, y1, x2, y2, stops } = gradient;
      return { id, tag, geometry, gradient: { x1, y1, x2, y2, stops } };
    });
  return {
    symbol: pick(0, SYMBOL_IDS),
    clyx: pick(5, CLYX_IDS),
    studio: pick(9, STUDIO_IDS),
  };
}

function renderTs({ symbol, clyx, studio }) {
  const list = (items) => JSON.stringify(items, null, 2);
  return `// Generated by scripts/logo.mjs from public/brand/logo-original.svg. Do not edit by hand.
// Run \`npm run logo:extract\` after the SVG changes; \`npm run logo:check\` fails if this file drifts.

export type LogoStop = { readonly offset: string; readonly color: string };

export type LogoGradient = {
  readonly x1: string;
  readonly y1: string;
  readonly x2: string;
  readonly y2: string;
  readonly stops: readonly LogoStop[];
};

export type LogoShape = {
  readonly id: string;
  readonly tag: "path" | "polygon";
  readonly geometry: string;
  readonly gradient: LogoGradient;
};

export const LOGO_VIEWBOX = "0 0 2000 2000";

export const SYMBOL_VIEWBOX = ${JSON.stringify(SYMBOL_VIEWBOX)};

export const LOGO_SYMBOL: readonly LogoShape[] = ${list(symbol)};

export const LOGO_CLYX: readonly LogoShape[] = ${list(clyx)};

export const LOGO_STUDIO: readonly LogoShape[] = ${list(studio)};
`;
}

function element(shape, fill) {
  const geometryAttr = shape.tag === "path" ? "d" : "points";
  return `  <${shape.tag} fill="${fill}" ${geometryAttr}="${shape.geometry}"/>`;
}

function renderMark({ symbol }) {
  const defs = symbol
    .map((shape, index) => {
      const { x1, y1, x2, y2, stops } = shape.gradient;
      const stopTags = stops
        .map((stop) => `<stop offset="${stop.offset}" stop-color="${stop.color}"/>`)
        .join("");
      return `    <linearGradient id="clyx-${index}" gradientUnits="userSpaceOnUse" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}">${stopTags}</linearGradient>`;
    })
    .join("\n");
  const shapes = symbol.map((shape, index) => element(shape, `url(#clyx-${index})`)).join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${SYMBOL_VIEWBOX}" role="img" aria-label="CLYX STUDIO">
  <defs>
${defs}
  </defs>
${shapes}
</svg>
`;
}

function renderMono({ symbol }) {
  const shapes = symbol.map((shape) => element(shape, "#F5F2F5")).join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${SYMBOL_VIEWBOX}" role="img" aria-label="CLYX STUDIO">
${shapes}
</svg>
`;
}

const svg = readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n");
const shapes = parse(svg);
const errors = validate(svg, shapes);
if (errors.length) {
  console.error(`logo-original.svg failed validation:\n- ${errors.join("\n- ")}`);
  process.exit(1);
}

const groups = grouped(shapes);
const outputs = [
  [OUT_TS, renderTs(groups)],
  [OUT_MARK, renderMark(groups)],
  [OUT_MONO, renderMono(groups)],
];

if (process.argv.includes("--write")) {
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log("Wrote logo.ts and symbol marks from logo-original.svg (5 symbol shapes, 10 letters, 15 gradients).");
} else {
  const lf = (text) => text.replace(/\r\n/g, "\n");
  const stale = outputs.filter(([file, text]) => {
    try {
      return lf(readFileSync(file, "utf8")) !== lf(text);
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Out of sync with logo-original.svg. Run npm run logo:extract.\n- ${stale.map(([file]) => file).join("\n- ")}`);
    process.exit(1);
  }
  console.log("Logo data matches logo-original.svg: 5 symbol shapes, 10 letters, 15 gradients.");
}
